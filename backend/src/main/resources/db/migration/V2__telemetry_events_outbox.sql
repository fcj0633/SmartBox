CREATE TABLE telemetry (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  box_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  node_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  boot_id BIGINT NOT NULL CHECK (boot_id BETWEEN 0 AND 4294967295),
  property_seq BIGINT NOT NULL CHECK (property_seq BETWEEN 1 AND 4294967295),
  device_ts BIGINT NULL DEFAULT NULL CHECK (device_ts >= 0),
  ts_src VARCHAR(16) NOT NULL,
  uptime_ms DECIMAL(20,0) NOT NULL CHECK (uptime_ms BETWEEN 0 AND 18446744073709551615),
  time_uncertainty_ms BIGINT NULL DEFAULT NULL CHECK (time_uncertainty_ms >= 0),
  CHECK ((ts_src='SNTP' AND device_ts IS NOT NULL AND time_uncertainty_ms IS NOT NULL) OR (ts_src='UNSYNCED' AND device_ts IS NULL AND time_uncertainty_ms IS NULL)),
  received_at BIGINT NOT NULL CHECK (received_at >= 0),
  payload JSON NOT NULL,
  created_at BIGINT NOT NULL CHECK (created_at >= 0),
  UNIQUE KEY uk_property (node_id,boot_id,property_seq),
  FOREIGN KEY (node_id,box_id) REFERENCES nodes(node_id,box_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  INDEX ix_telemetry_box (box_id,received_at,id),
  INDEX ix_telemetry_node (node_id,received_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE node_latest (
  box_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  node_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  boot_id BIGINT NOT NULL CHECK (boot_id BETWEEN 0 AND 4294967295),
  property_seq BIGINT NOT NULL CHECK (property_seq BETWEEN 1 AND 4294967295),
  device_ts BIGINT NULL DEFAULT NULL CHECK (device_ts >= 0),
  ts_src VARCHAR(16) NOT NULL,
  uptime_ms DECIMAL(20,0) NOT NULL CHECK (uptime_ms BETWEEN 0 AND 18446744073709551615),
  time_uncertainty_ms BIGINT NULL DEFAULT NULL CHECK (time_uncertainty_ms >= 0),
  CHECK ((ts_src='SNTP' AND device_ts IS NOT NULL AND time_uncertainty_ms IS NOT NULL) OR (ts_src='UNSYNCED' AND device_ts IS NULL AND time_uncertainty_ms IS NULL)),
  received_at BIGINT NOT NULL CHECK (received_at >= 0),
  payload JSON NOT NULL,
  PRIMARY KEY (node_id),
  updated_at BIGINT NOT NULL CHECK (updated_at >= 0),
  FOREIGN KEY (node_id,box_id) REFERENCES nodes(node_id,box_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  INDEX ix_latest_box (box_id,node_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE events (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  box_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  node_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  boot_id BIGINT NOT NULL CHECK (boot_id BETWEEN 0 AND 4294967295),
  event_seq BIGINT NOT NULL CHECK (event_seq BETWEEN 1 AND 4294967295),
  device_ts BIGINT NULL DEFAULT NULL CHECK (device_ts >= 0),
  ts_src VARCHAR(16) NOT NULL,
  uptime_ms DECIMAL(20,0) NOT NULL CHECK (uptime_ms BETWEEN 0 AND 18446744073709551615),
  time_uncertainty_ms BIGINT NULL DEFAULT NULL CHECK (time_uncertainty_ms >= 0),
  CHECK ((ts_src='SNTP' AND device_ts IS NOT NULL AND time_uncertainty_ms IS NOT NULL) OR (ts_src='UNSYNCED' AND device_ts IS NULL AND time_uncertainty_ms IS NULL)),
  received_at BIGINT NOT NULL CHECK (received_at >= 0),
  created_at BIGINT NOT NULL CHECK (created_at >= 0),
  type VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK (type IN ('ENV_HIGH','ENV_LOW','ENV_RECOVERED','POSE_CHANGED','IMPACT','DOOR_EVIDENCE','SENTRY_INTRUSION','GEOFENCE_EXIT','GEOFENCE_ENTER','STORAGE_OVERFLOW','DEVICE_FAULT')),
  src TEXT NOT NULL,
  level VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK (level IN ('INFO','WARNING','CRITICAL')),
  replayed BOOLEAN NOT NULL CHECK (replayed IN (0,1)),
  data JSON NOT NULL,
  raw_event JSON NOT NULL,
  content_hash BINARY(32) NOT NULL,
  UNIQUE KEY uk_event (node_id,boot_id,event_seq),
  UNIQUE KEY uk_event_box (id,box_id),
  FOREIGN KEY (node_id,box_id) REFERENCES nodes(node_id,box_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  INDEX ix_event_received (box_id,received_at,id),
  INDEX ix_event_device (box_id,device_ts,id),
  INDEX ix_event_filter (box_id,type,level,received_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE processing_outbox (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  event_id BIGINT NOT NULL,
  task_type VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','PROCESSING','RETRY','DONE')),
  attempts INT NOT NULL DEFAULT 0 CHECK (attempts>=0),
  next_attempt_at BIGINT NOT NULL CHECK (next_attempt_at >= 0),
  locked_until BIGINT NULL DEFAULT NULL CHECK (locked_until >= 0),
  lock_owner VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NULL DEFAULT NULL,
  last_error_code VARCHAR(64) NULL DEFAULT NULL,
  created_at BIGINT NOT NULL CHECK (created_at >= 0),
  updated_at BIGINT NOT NULL CHECK (updated_at >= 0),
  UNIQUE KEY uk_event_task (event_id,task_type),
  FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  INDEX ix_outbox_due (status,next_attempt_at,id),
  INDEX ix_outbox_lease (status,locked_until,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
