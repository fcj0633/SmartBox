CREATE TABLE command_operations (
  operation_id VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin PRIMARY KEY,
  box_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  requested_by BIGINT NOT NULL,
  cmd VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL CHECK (cmd IN ('sentry','profile','gps_mode','output','calibrate')),
  params JSON NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','RUNNING','SUCCEEDED','PARTIAL','FAILED','EXPIRED')),
  created_at BIGINT NOT NULL CHECK (created_at >= 0),
  updated_at BIGINT NOT NULL CHECK (updated_at >= 0),
  UNIQUE KEY uk_operation_box (operation_id,box_id),
  FOREIGN KEY (box_id) REFERENCES boxes(box_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (requested_by) REFERENCES users(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  INDEX ix_operation_box (box_id,created_at,operation_id),
  INDEX ix_operation_status (status,updated_at,operation_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE node_commands (
  request_id VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin PRIMARY KEY,
  operation_id VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
  box_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  node_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  target_caps SMALLINT NOT NULL CHECK (target_caps BETWEEN 1 AND 127),
  issued_at BIGINT NOT NULL CHECK (issued_at >= 0),
  expires_at BIGINT NOT NULL CHECK (expires_at >= 0),
  CHECK (expires_at>issued_at),
  status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','RUNNING','SUCCEEDED','FAILED','EXPIRED')),
  ack_boot_id BIGINT NULL DEFAULT NULL CHECK (ack_boot_id BETWEEN 0 AND 4294967295),
  ack_received_at BIGINT NULL DEFAULT NULL CHECK (ack_received_at >= 0),
  ack_ts BIGINT NULL DEFAULT NULL CHECK (ack_ts >= 0),
  ack_ts_src VARCHAR(16) NULL DEFAULT NULL,
  ack_uptime_ms DECIMAL(20,0) NULL DEFAULT NULL CHECK (ack_uptime_ms BETWEEN 0 AND 18446744073709551615),
  ack_time_uncertainty_ms BIGINT NULL DEFAULT NULL CHECK (ack_time_uncertainty_ms >= 0),
  result VARCHAR(16) NULL DEFAULT NULL CHECK (result IN ('ok','ignored','busy','error','expired')),
  code VARCHAR(64) NULL DEFAULT NULL,
  actual_state JSON NULL,
  created_at BIGINT NOT NULL CHECK (created_at >= 0),
  updated_at BIGINT NOT NULL CHECK (updated_at >= 0),
  CHECK ((ack_received_at IS NULL AND ack_boot_id IS NULL AND ack_ts IS NULL AND ack_ts_src IS NULL AND ack_uptime_ms IS NULL AND ack_time_uncertainty_ms IS NULL AND result IS NULL AND code IS NULL AND actual_state IS NULL) OR (ack_received_at IS NOT NULL AND ack_boot_id IS NOT NULL AND ack_uptime_ms IS NOT NULL AND result IS NOT NULL AND code IS NOT NULL AND actual_state IS NOT NULL AND ((ack_ts_src='SNTP' AND ack_ts IS NOT NULL AND ack_time_uncertainty_ms IS NOT NULL) OR (ack_ts_src='UNSYNCED' AND ack_ts IS NULL AND ack_time_uncertainty_ms IS NULL)))),
  UNIQUE KEY uk_operation_node (operation_id,node_id),
  FOREIGN KEY (operation_id,box_id) REFERENCES command_operations(operation_id,box_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (node_id,box_id) REFERENCES nodes(node_id,box_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  INDEX ix_command_expiry (status,expires_at,request_id),
  INDEX ix_command_node (node_id,created_at,request_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE idempotency_records (
  user_id BIGINT NOT NULL,
  box_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  idempotency_key VARBINARY(64) NOT NULL CHECK (OCTET_LENGTH(idempotency_key) BETWEEN 1 AND 64),
  request_hash BINARY(32) NOT NULL,
  operation_id VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
  created_at BIGINT NOT NULL CHECK (created_at >= 0),
  expires_at BIGINT NOT NULL CHECK (expires_at >= 0),
  CHECK (expires_at-created_at>=86400000),
  PRIMARY KEY (user_id,box_id,idempotency_key),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (operation_id,box_id) REFERENCES command_operations(operation_id,box_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  INDEX ix_idempotency_expiry (expires_at,user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
CREATE TABLE audit_logs (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  actor_user_id BIGINT NULL DEFAULT NULL,
  attempted_username VARCHAR(128) NULL DEFAULT NULL,
  box_id VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NULL DEFAULT NULL,
  target_box_id VARCHAR(128) NULL DEFAULT NULL,
  action VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  result VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_id VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
  occurred_at BIGINT NOT NULL CHECK (occurred_at >= 0),
  details JSON NULL,
  FOREIGN KEY (actor_user_id) REFERENCES users(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  FOREIGN KEY (box_id) REFERENCES boxes(box_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  INDEX ix_audit_time (occurred_at,id),
  INDEX ix_audit_user (actor_user_id,occurred_at,id),
  INDEX ix_audit_request (request_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
